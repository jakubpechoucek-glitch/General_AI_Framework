"""Keeps the user guide in sync with the app (see docs/guide/MAINTAINING.md)."""
import re
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

ROOT = Path(__file__).resolve().parent.parent
GUIDE = ROOT / "docs" / "guide"
TEMPLATES = ROOT / "app" / "templates"


def _ids(html: str) -> set[str]:
    return set(re.findall(r'id="([^"]+)"', html))


@pytest.fixture(scope="module")
def client(seeded):
    from app.main import app
    return TestClient(app)


def test_every_guide_page_renders(client):
    from app.routes.help import PAGES
    assert client.get("/help").status_code == 200
    for slug, *_ in PAGES:
        assert (GUIDE / f"{slug}.md").exists(), slug
        r = client.get(f"/help/{slug}")
        assert r.status_code == 200, slug
        assert "<h1" in r.text


def test_images_exist_and_match_screenshot_definitions():
    from scripts.screenshots import SHOTS
    defined = {s[0] for s in SHOTS}
    assert len(defined) == len(SHOTS), "duplicate screenshot names"
    from app.routes.help import PAGES
    referenced = set()
    for md in [GUIDE / f"{slug}.md" for slug, *_ in PAGES]:
        for img in re.findall(r"!\[[^\]]*\]\(img/([^)]+)\.png\)", md.read_text()):
            assert (GUIDE / "img" / f"{img}.png").exists(), f"{md.name}: missing img/{img}.png"
            assert img in defined, f"{md.name}: img/{img}.png is not generated by scripts/screenshots.py"
            referenced.add(img)
    assert not defined - referenced, f"screenshots not used in the guide: {defined - referenced}"
    on_disk = {p.stem for p in (GUIDE / "img").glob("*.png")}
    assert not on_disk - defined, f"stale screenshots not in SHOTS: {on_disk - defined}"


def test_links_between_guide_pages(client):
    for md in GUIDE.glob("*.md"):
        for page, anchor in re.findall(r"\]\(([a-z0-9-]+)\.md(?:#([^)]+))?\)", md.read_text()):
            assert (GUIDE / f"{page}.md").exists(), f"{md.name} -> {page}.md"
            if anchor and page not in ("README", "MAINTAINING"):
                assert anchor in _ids(client.get(f"/help/{page}").text), f"{md.name} -> {page}#{anchor}"
        for anchor in re.findall(r"\]\(#([^)]+)\)", md.read_text()):
            assert anchor in _ids(client.get(f"/help/{md.stem}").text), f"{md.name} -> #{anchor}"


def test_contextual_help_links_in_templates(client):
    links = set()
    for t in TEMPLATES.rglob("*.html"):
        text = t.read_text()
        links |= set(re.findall(r'help\("([a-z0-9-]+(?:#[a-z0-9-]+)?)"', text))
        links |= set(re.findall(r'href="/help/([a-z0-9-]+(?:#[a-z0-9-]+)?)"', text))
    assert links, "expected contextual help links"
    for link in links:
        page, _, anchor = link.partition("#")
        r = client.get(f"/help/{page}")
        assert r.status_code == 200, link
        if anchor:
            assert anchor in _ids(r.text), f"help link {link}: heading not found"


